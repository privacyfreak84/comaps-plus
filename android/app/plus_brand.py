#!/usr/bin/env python3
"""Tabula branding layer for the Android app.

The app's strings (values*/strings.xml in every translation) and its FAQ and copyright pages
(data/faq.html, data/copyright.html) come from CoMaps and are updated there all the time. Editing them
in place would make every upstream translation update conflict with this fork. Instead the build runs
this script and adds its output as a higher-priority resource and asset folder (see build.gradle.kts):

  res    For every string that mentions CoMaps or links to comaps.app, writes the same string with the
         app's name and links. Upstream files stay untouched.
  assets Writes faq.html and copyright.html the same way.

Links: comaps.app downloads go to the project's latest release, support addresses and issue trackers to
its issues page, and other comaps.app pages to its home page. Map download servers (cdn-*.comaps.app,
mapgen-*.comaps.app) are kept: maps still come from CoMaps. CoMaps is credited in strings_plus.xml,
which this script doesn't read.

Usage: plus_brand.py res|assets SRC OUT NAME HOME_URL
  SRC  res: the app's src/main/res; assets: the folder holding faq.html and copyright.html
  HOME_URL ends with '/'; HOME_URL + 'issues' and HOME_URL + 'releases/latest' must exist.
"""

import os
import re
import shutil
import sys

# Strings that mention CoMaps but must keep their value: preference keys and the map server hint.
KEEP = {'pref_about', 'download_resources_custom_url_hint'}
STRING_FILES = ('strings.xml', 'donottranslate.xml')
HTML_FILES = ('faq.html', 'copyright.html')

ELEMENT = re.compile(r'<(string-array|plurals|string)\b[^>]*?\bname="([^"]+)"[^>]*>.*?</\1>', re.S)
# A comaps.app address with or without scheme; subdomains other than www (map servers) don't match.
SITE = re.compile(r'(?:https?://(?:www\.)?|(?<![\w.@/-])(?:www\.)?)comaps\.app(?![\w-])(/[^\s"\'<>)]*)?', re.I)
MAIL = re.compile(r'(?:mailto:)?\b[\w.+-]+@comaps\.app\b', re.I)
CODEBERG = re.compile(r'(?:https?://)?codeberg\.org/comaps/comaps(/issues[^\s"\'<>)]*)?(/[^\s"\'<>)]*)?', re.I)
# Text that must not get the name replaced: addresses and URLs of any kind.
PROTECTED = re.compile(r'(?:https?://|mailto:|www\.)[^\s"\'<>]+|[\w.-]+\.(?:app|at|org|com|net|me)\b[^\s"\'<>]*', re.I)
NAME = re.compile(r'comaps', re.I)


def relink(text, home):
    issues = home + 'issues'
    text = CODEBERG.sub(lambda m: issues if m.group(1) else home, text)
    text = MAIL.sub(issues, text)

    def site(m):
        path = (m.group(1) or '').lower()
        if re.match(r'/(?:[a-z]{2}(?:-[a-z]+)?/)?download', path):
            return home + 'releases/latest'
        return home

    return SITE.sub(site, text)


def rename(text, name):
    out, last = [], 0
    for m in PROTECTED.finditer(text):
        out.append(NAME.sub(name, text[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(NAME.sub(name, text[last:]))
    return ''.join(out)


def brand(text, name, home):
    return rename(relink(text, home), name)


def needs(text):
    return NAME.search(text) is not None


def do_res(src, out, name, home):
    count = 0
    for d in sorted(os.listdir(src)):
        if not d.startswith('values'):
            continue
        elements = []
        for f in STRING_FILES:
            path = os.path.join(src, d, f)
            if not os.path.isfile(path):
                continue
            with open(path, encoding='utf-8') as fh:
                data = fh.read()
            for m in ELEMENT.finditer(data):
                if m.group(2) in KEEP or not needs(m.group(0)):
                    continue
                branded = brand(m.group(0), name, home)
                if branded != m.group(0):
                    elements.append(branded)
        if not elements:
            continue
        os.makedirs(os.path.join(out, d), exist_ok=True)
        with open(os.path.join(out, d, 'strings.xml'), 'w', encoding='utf-8') as fh:
            fh.write('<?xml version="1.0" encoding="utf-8"?>\n')
            fh.write('<!-- Generated by android/app/plus_brand.py; do not edit. -->\n')
            fh.write('<resources xmlns:tools="http://schemas.android.com/tools">\n')
            for e in elements:
                fh.write('    ' + e + '\n')
            fh.write('</resources>\n')
        count += len(elements)
    print(f'plus_brand: {count} strings branded as {name}')


def do_assets(src, out, name, home):
    os.makedirs(out, exist_ok=True)
    for f in HTML_FILES:
        path = os.path.join(src, f)
        if not os.path.isfile(path):
            continue
        with open(path, encoding='utf-8') as fh:
            data = fh.read()
        with open(os.path.join(out, f), 'w', encoding='utf-8') as fh:
            fh.write(brand(data, name, home))
    print(f'plus_brand: {", ".join(HTML_FILES)} branded as {name}')


def main(argv):
    if len(argv) != 6 or argv[1] not in ('res', 'assets') or not argv[5].endswith('/'):
        sys.exit(__doc__)
    mode, src, out, name, home = argv[1:]
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)
    (do_res if mode == 'res' else do_assets)(src, out, name, home)


if __name__ == '__main__':
    main(sys.argv)
